// Adapt the first ten getdesign.md entries (2026-10-14) to the shared playground.
const fs = require('node:fs');
const profiles = [
  ['mobbin', 'Mobbin', 'Gallery monochrome', 24, 24, 9999, 9999, 24, 24, 652, 1.38],
  ['1win', '1win', 'Dense dark rails', 16, 16, 10, 8, 16, 16, 800, 1.4],
  ['aljazeera', 'Al Jazeera', 'Flat news editorial', 0, 0, 9999, 4, 16, 16, 700, 1.5],
  ['dji', 'DJI', 'Engineering showroom', 0, 8, 9999, 8, 24, 16, 600, 1.5],
  ['jobright', 'Jobright', 'Spring mint startup', 40, 24, 36, 16, 32, 24, 700, 1.6],
  ['mercury', 'Mercury', 'Ink violet banking', 16, 12, 40, 8, 24, 24, 480, 1.4],
  ['mydealz', 'mydealz', 'Dense community feed', 8, 8, 540, 540, 16, 16, 700, 1.5],
  ['nerdwallet', 'NerdWallet', 'Spruce comparison', 8, 4, 4, 4, 24, 20, 700, 1.5],
  ['oracle', 'Oracle', 'Warm enterprise editorial', 15, 8, 4, 6, 24, 24, 400, 1.4],
  ['oura', 'Oura', 'Warm paper wellness', 40, 24, 9999, 12, 32, 32, 400, 1.5]
];
let css = '/* Generated by build-catalog-themes.cjs; source guides are in themes/. */\n';
const metadata = {};
for (const [id, label, profile, panel, card, button, control, padding, gap, weight, leading] of profiles) {
  const guide = fs.readFileSync(`themes/${id}/DESIGN.md`, 'utf8');
  const block = guide.match(/\ncolors:\n([\s\S]*?)\ntypography:/)[1];
  const colors = Object.fromEntries([...block.matchAll(/  ([\w-]+): "(#[\da-f]+)"/gi)].map(m => [m[1], m[2]]));
  const pick = (...keys) => keys.map(k => colors[k]).find(Boolean);
  const dark = id === '1win' || id === 'mercury';
  const fonts = [...guide.matchAll(/fontFamily: (.+)/g)].map(m => m[1]);
  const body = id === 'oura' ? 'AkkuratLL' : id === 'jobright' ? 'Inter' : fonts[0];
  const heading = id === 'oracle' ? 'Georgia' : fonts[0];
  const serif = id === 'oura' || id === 'oracle';
  const primary = ['aljazeera', 'jobright'].includes(id) ? colors.ink : colors.primary;
  const muted = id === 'mydealz' ? colors.body : id === 'oura' ? colors.stone : id === 'oracle' ? '#59524b' : pick('text-muted', 'muted', 'slate', 'ink-secondary');
  const tokens = {
    bg: dark && id === 'mercury' ? colors.night : colors.canvas,
    surface: dark && id === 'mercury' ? colors['night-raised'] : pick('surface', 'canvas'),
    'surface-strong': dark ? pick('surface', 'night-raised') : pick('canvas-mint', 'mint-50', 'canvas-warm', 'canvas-soft', 'canvas-tint', 'surface-grey', 'soft', 'field', 'discount-surface'),
    text: dark && id === 'mercury' ? colors['on-dark'] : colors.ink,
    muted: dark && id === 'mercury' ? colors.fog : muted,
    border: dark && id === 'mercury' ? colors.slate : pick('card-border', 'hairline-strong', 'hairline'),
    primary, 'primary-strong': pick('primary-pressed', 'primary-deep', 'green-strong') || primary,
    secondary: id === '1win' ? colors.secondary : dark ? pick('night-raised', 'surface') : pick('stone', 'canvas-soft', 'soft', 'surface-soft', 'mint-100', 'canvas-warm', 'field', 'surface-grey', 'surface'),
    accent: pick('accent', 'primary', 'gold'), 'on-primary': '#ffffff',
    success: dark ? '#69d391' : '#197344', warning: dark ? '#f0ca62' : '#855600',
    danger: pick('hot', 'live-red') || (dark ? '#ff9696' : '#b52632'),
    shadow: 'transparent', ring: pick('focus', 'accent', 'primary'),
    'profile-label': profile, 'font-label': `${heading} / ${body} (local fallbacks)`,
    'font-body': `"${body}", "Segoe UI", Arial, sans-serif`,
    'font-heading': `"${heading}", ${serif ? 'Georgia, serif' : '"Segoe UI", Arial, sans-serif'}`,
    'heading-weight': weight, 'heading-tracking': id === 'dji' ? '-0.03em' : '0',
    'body-leading': leading, 'label-tracking': '0', 'label-case': 'none',
    'radius-panel': `${panel}px`, 'radius-card': `${card}px`, 'radius-button': `${button}px`,
    'radius-control': `${control}px`, 'radius-badge': id === 'nerdwallet' ? '2px' : '9999px',
    'space-card': `${padding}px`, 'space-gap': `${gap}px`, 'section-space': id === 'jobright' ? '96px' : '80px',
    'panel-elevation': 'none', 'card-elevation': 'none', 'elevation-label': 'Flat surface layers', 'hover-lift': '0px'
  };
  const selector = `:root[data-theme="${id}"]`;
  css += `${selector} {\n  color-scheme: ${dark ? 'dark' : 'light'};\n`;
  for (const [key, value] of Object.entries(tokens)) {
    if (value === undefined) throw Error(`${id}: missing ${key}`);
    css += `  --${key}: ${value};\n`;
  }
  for (const [key, value] of Object.entries(colors)) css += `  --reference-${key}: ${value};\n`;
  css += '}\n';
  css += `${selector} :is(.primary-button, .theme-option.is-active, .x-button-primary) { color: var(--on-primary); background: var(--primary); }\n`;
  css += `${selector} .secondary-button { color: ${id === '1win' || id === 'oura' ? '#ffffff' : 'var(--text)'}; }\n`;
  css += `${selector} .x-gallery { --x-on-primary: var(--on-primary); --x-link: ${dark ? (id === 'mercury' ? colors.periwinkle : '#85b9ff') : pick('link', 'stone', 'ink')}; }\n`;
  if (id === 'jobright' || id === 'aljazeera') css += `${selector} .section-kicker { border-left: 4px solid var(--accent); padding-left: 12px; }\n`;
  if (id === 'mobbin' || id === 'mydealz') css += `${selector} #workspace-search { border-radius: 9999px; }\n`;
  metadata[id] = { label, accent: colors.primary, colors };
}
fs.writeFileSync('catalog-themes.css', css);
fs.writeFileSync('catalog-themes.js', `// Generated catalog theme metadata and reference palette.\nconst catalogThemes = ${JSON.stringify(metadata, null, 2)};\n`);
